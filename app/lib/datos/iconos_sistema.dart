const _icFichero = 13;

/// Las 12 filas (u16, bit (w-1) = píxel de la izquierda) y el ancho del
/// icono genérico `n`, empaquetados igual que en sh_iconos_init().
(int, List<int>) iconoGenerico(int n) {
  final arte = _arte[n < _arte.length ? n : _icFichero];
  final w = arte.first.length;
  final filas = List<int>.filled(12, 0);
  // Los pequeños (carpeta, fichero…) miden 7 filas: se centran en las 12.
  final y0 = (12 - arte.length) ~/ 2;
  for (var f = 0; f < arte.length && f < 12; f++) {
    var b = 0;
    for (var c = 0; c < w && c < arte[f].length; c++) {
      if (arte[f][c] == '#') b |= 1 << (w - 1 - c);
    }
    filas[y0 + f] = b;
  }
  return (w, filas);
}

/// La cabecera tal cual si trae icono propio; si no, una copia con el
/// icono genérico que pidió, para pintarla con el mismo pintor.
SenCab conIcono(SenCab c) {
  if (c.traeIcono) return c;
  final (w, filas) = iconoGenerico(c.iconoGen);
  return SenCab(
    nombre: c.nombre,
    iconoAn: w,
    iconoFilas: filas,
    iconoGen: c.iconoGen,
    tamFich: c.tamFich,
    perfil: c.perfil,
    apiMayor: c.apiMayor,
    apiMenor: c.apiMenor,
    verApp: c.verApp,
    maquina: c.maquina,
    caps: c.caps,
    anMin: c.anMin,
    alMin: c.alMin,
    tamRec: c.tamRec,
    crcRec: c.crcRec,
    crcCuerpo: c.crcCuerpo,
    crcCab: c.crcCab,
  );
}
